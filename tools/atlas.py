"""Packs the hedgehog-mode sprites the game draws into one texture for the Wii.

The hedgehog-mode sprite sheet is 2000 pixels wide and a Wii texture is at
most 1024, so the sprites are copied, pixel for pixel, into a smaller sheet.
Each sprite sits at the top-left corner of an 80x80 cell.

Pickups are PostHog team crests, which are vector art published as 115-pixel
PNGs. They are scaled down to fit a cell.

Usage: atlas.py <hedgehog-mode assets dir> <crests dir> <output dir>
"""

import json
import sys
from pathlib import Path

from PIL import Image

CELL = 80
COLUMNS = 12
HEDGEHOG_ANIMATIONS = ["idle", "walk", "fall", "death"]
PICKUP_SIZE = 64
PICKUP_CRESTS = [
    "feature-flags",
    "experiments",
    "replay",
    "product-analytics",
    "web-analytics",
    "surveys",
    "error-tracking",
    "ai-observability",
    "workflows",
    "managed-warehouse",
]


def main(source: Path, crests: Path, output: Path) -> None:
    sheet = Image.open(source / "sprites.png").convert("RGBA")
    layout = json.loads((source / "sprites.json").read_text())
    animations: dict[str, list[str]] = layout["animations"]

    groups: dict[str, list[str]] = {name: animations[f"skins/default/{name}/tile"] for name in HEDGEHOG_ANIMATIONS}
    groups["fire"] = animations["overlays/fire/tile"]
    groups["hogzilla"] = animations["skins/hogzilla/walk/tile"]

    cells: list[Image.Image] = []
    constants: list[str] = []
    for name, keys in groups.items():
        constants.append(f"ATLAS_{name.upper()}_FIRST = {len(cells)}")
        constants.append(f"ATLAS_{name.upper()}_COUNT = {len(keys)}")
        for key in keys:
            box = layout["frames"][key]["frame"]
            if box["w"] > CELL or box["h"] > CELL:
                raise SystemExit(f"{key} does not fit a {CELL}x{CELL} cell")
            cell = Image.new("RGBA", (CELL, CELL), (0, 0, 0, 0))
            cell.paste(sheet.crop((box["x"], box["y"], box["x"] + box["w"], box["y"] + box["h"])), (0, 0))
            cells.append(cell)

    constants.append(f"ATLAS_PICKUP_FIRST = {len(cells)}")
    constants.append(f"ATLAS_PICKUP_COUNT = {len(PICKUP_CRESTS)}")
    for name in PICKUP_CRESTS:
        crest = Image.open(crests / f"{name}.png").convert("RGBA")
        cell = Image.new("RGBA", (CELL, CELL), (0, 0, 0, 0))
        cell.paste(crest.resize((PICKUP_SIZE, PICKUP_SIZE), Image.Resampling.LANCZOS), (0, 0))
        cells.append(cell)

    # Flat rectangles are drawn from this cell, so they need no second texture.
    constants.append(f"ATLAS_WHITE = {len(cells)}")
    cells.append(Image.new("RGBA", (CELL, CELL), (255, 255, 255, 255)))

    rows = -(-len(cells) // COLUMNS)
    atlas = Image.new("RGBA", (COLUMNS * CELL, rows * CELL), (0, 0, 0, 0))
    for index, cell in enumerate(cells):
        atlas.paste(cell, (index % COLUMNS * CELL, index // COLUMNS * CELL))
    if atlas.width > 1024 or atlas.height > 1024:
        raise SystemExit(f"the atlas is {atlas.width}x{atlas.height}, and a Wii texture is at most 1024x1024")

    output.mkdir(parents=True, exist_ok=True)
    atlas.save(output / "atlas.png")
    constants = [
        f"ATLAS_CELL = {CELL}",
        f"ATLAS_COLUMNS = {COLUMNS}",
        f"ATLAS_WIDTH = {atlas.width}",
        f"ATLAS_HEIGHT = {atlas.height}",
        *constants,
    ]
    body = "".join(f"    {constant},\n" for constant in constants)
    (output / "atlas.h").write_text(
        f"/* Generated by tools/atlas.py. */\n#ifndef ATLAS_H\n#define ATLAS_H\n\nenum {{\n{body}}};\n\n#endif\n"
    )


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3]))
